  "export async function signIn(page: Page, login = process.env.ODOO_LOGIN ?? 'admin', password = process.env.ODOO_PASSWORD ?? 'admin'): Promise<void> {",
  "  await page.goto('/web/login');",
  "  await page.fill('input[name=\"login\"]', login);",
  "  await page.fill('input[name=\"password\"]', password);",
  "  await page.click('button[type=\"submit\"]');",
  "  await expect(page.locator('.o_main_navbar')).toBeVisible({ timeout: 30_000 });",
  "}",
  "",
  "async function settled(page: Page): Promise<void> {",
  "  await expect(page.locator('.o_action_manager .o_view_controller').first()).toBeVisible({ timeout: 30_000 });",
  "  await expect(page.locator('.o_loading_indicator, .o_blockUI')).toHaveCount(0, { timeout: 30_000 });",
  "}",
  "",
  "export async function openAction(page: Page, action: string, options: { newRecord?: boolean } = {}): Promise<void> {",
  "  await page.goto(`/odoo/action-${action}${options.newRecord ? '/new' : ''}`);",
  "  await settled(page);",
  "}",
  "",
  "export async function openRecord(page: Page, action: string, id: number): Promise<void> {",
  "  await page.goto(`/odoo/action-${action}/${id}`);",
  "  await settled(page);",
  "}",
  "",
  "export function field(where: Where, name: string): Locator {",
  "  return where.locator(`.o_field_widget[name=\"${name}\"]`).first();",
  "}",
  "",
  "export async function fill(where: Where, name: string, value: string): Promise<void> {",
  "  const input = field(where, name).locator('input, textarea, [contenteditable=\"true\"]').first();",
  "  await input.fill(value);",
  "  await input.press('Tab');",
  "}",
  "",
  "export async function choose(where: Where, name: string, text: string, options: { create?: boolean } = {}): Promise<void> {",
  "  const input = field(where, name).locator('input').first();",
  "  await input.click();",
  "  await input.fill(text);",
  "  const page = 'page' in where ? where.page() : where;",
  "  const items = page.locator('.o-autocomplete--dropdown-item');",
  "  const item = options.create",
  "    ? items.filter({ hasText: `Create \"${text}\"` })",
  "    : items.filter({ hasText: text }).filter({ hasNotText: /^(Create|Search More)/ });",
  "  await item.first().click();",
  "  await expect(items).toHaveCount(0);",
  "}",
  "",
  "export async function tick(where: Where, name: string, on = true): Promise<void> {",
  "  const box = field(where, name).locator('input[type=\"checkbox\"]');",
  "  if ((await box.isChecked()) !== on) await box.click({ force: true });",
  "  await expect(box).toBeChecked({ checked: on });",
  "}",
  "",
  "export async function pick(where: Where, name: string, label: string): Promise<void> {",
  "  const widget = field(where, name);",
  "  const select = widget.locator('select');",
  "  if (await select.count()) {",
  "    await select.selectOption({ label });",
  "    return;",
  "  }",
  "  await widget.getByLabel(label, { exact: true }).check({ force: true });",
  "}",
  "",
  "export async function addLine(page: Page, name: string, values: Record<string, string | { choose: string; create?: boolean }>): Promise<void> {",
  "  await field(page, name).locator('.o_field_x2many_list_row_add a').first().click();",
  "  const row = field(page, name).locator('.o_selected_row');",
  "  await expect(row).toBeVisible();",
  "  for (const [column, value] of Object.entries(values)) {",
  "    if (typeof value === 'string') await fill(row, column, value);",
  "    else await choose(row, column, value.choose, value.create ? { create: true } : {});",
  "  }",
  "}",
  "",
  "export async function save(page: Page): Promise<number> {",
  "  const button = page.locator('.o_form_button_save');",
  "  if (await button.isVisible()) await button.click();",
  "  await expect(button).toBeHidden();",
  "  await expect(page.locator('.o_form_view .o_field_invalid')).toHaveCount(0);",
  "  await expect(page).toHaveURL(/\\/\\d+(\\?|$)/);",
  "  return recordId(page);",
  "}",
  "",
  "export function recordId(page: Page): number {",
  "  const found = new URL(page.url()).pathname.match(/\\/(\\d+)\\/?$/);",
  "  if (!found) throw new Error(`There is no saved record in ${page.url()}`);",
  "  return Number(found[1]);",
  "}",
  "",
  "export async function press(page: Page, button: string): Promise<void> {",
  "  const byName = page.locator(`.o_form_view button[name=\"${button}\"]:visible`);",
  "  const target = (await byName.count()) ? byName.first() : page.locator('.o_form_view').getByRole('button', { name: button, exact: true }).first();",
  "  await target.click();",
  "  await expect(page.locator('.o_loading_indicator, .o_blockUI')).toHaveCount(0, { timeout: 30_000 });",
  "}",
  "",
  "export async function smartButton(page: Page, text: string): Promise<void> {",
  "  await page.locator('.oe_stat_button').filter({ hasText: text }).first().click();",
  "  await settled(page);",
  "}",
  "",
  "export async function reportHtml(page: Page, report: string, ids: number | readonly number[]): Promise<Locator> {",
  "  const list = (Array.isArray(ids) ? ids : [ids]).join(',');",
  "  const response = await page.goto(`/report/html/${report}/${list}`);",
  "  if (!response?.ok()) throw new Error(`The report ${report} for ${list} answered ${response?.status()}`);",
  "  return page.locator('main, .page, body').first();",
  "}",
