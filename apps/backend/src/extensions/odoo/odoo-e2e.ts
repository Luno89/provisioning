export const ODOO_E2E_HELPERS_AT = '/usr/local/share/koala/odoo.ts';

export const ODOO_E2E_SCRIPT = [
  "#!/bin/sh",
  "set -eu",
  "usage() {",
  "  echo \"usage: odoo-e2e [--keep] <module[,module]> <spec-or-dir> [more specs]   (run from the repository root; addons in ./addons)\" >&2",
  "  echo \"       odoo-e2e --stop   (stops the Odoo that --keep left running)\" >&2",
  "  exit 2",
  "}",
  "kept=/tmp/odoo-e2e-kept",
  "ODOO_E2E_HELPERS=\"${ODOO_E2E_HELPERS:-" + ODOO_E2E_HELPERS_AT + "}\"",
  "pgbin=$(ls -d /usr/lib/postgresql/*/bin | sort -V | tail -1)",
  "stop_kept() {",
  "  [ -f \"$kept/odoo.pid\" ] && kill \"$(cat \"$kept/odoo.pid\")\" 2>/dev/null || true",
  "  \"$pgbin/pg_ctl\" -D \"$kept/pg\" -m fast stop >/dev/null 2>&1 || true",
  "  rm -rf \"$kept\"",
  "}",
  "keep=0",
  "if [ \"${1:-}\" = \"--stop\" ]; then",
  "  stop_kept",
  "  echo \"odoo-e2e: stopped the kept Odoo\"",
  "  exit 0",
  "fi",
  "if [ \"${1:-}\" = \"--keep\" ]; then keep=1; shift; fi",
  "[ $# -ge 2 ] || usage",
  "modules=\"$1\"",
  "shift",
  "addons=\"${ODOO_ADDONS:-$PWD/addons}\"",
  "if [ ! -f \"$PWD/e2e/odoo.ts\" ] && [ -f \"$ODOO_E2E_HELPERS\" ]; then",
  "  mkdir -p \"$PWD/e2e\"",
  "  cp \"$ODOO_E2E_HELPERS\" \"$PWD/e2e/odoo.ts\"",
  "  echo \"odoo-e2e: added e2e/odoo.ts, the Odoo helpers a spec imports from './odoo' (signIn, openAction, fill, choose, addLine, save, press, smartButton, reportHtml); commit it with your specs\"",
  "fi",
  "fingerprint=$(find \"$addons\" -type f -not -path '*/__pycache__/*' -not -name '*.pyc' -print0 2>/dev/null | sort -z | xargs -0 md5sum 2>/dev/null | md5sum | cut -d' ' -f1)",
  "odoo_pid=\"\"",
  "if [ \"$keep\" = 1 ]; then",
  "  state=\"$kept\"",
  "  port=${ODOO_E2E_PORT:-8069}",
  "else",
  "  state=$(mktemp -d /tmp/odoo-e2e.XXXXXX)",
  "  port=${ODOO_E2E_PORT:-8079}",
  "fi",
  "cleanup() {",
  "  [ \"$keep\" = 1 ] && return 0",
  "  [ -n \"$odoo_pid\" ] && kill \"$odoo_pid\" 2>/dev/null || true",
  "  \"$pgbin/pg_ctl\" -D \"$state/pg\" -m fast stop >/dev/null 2>&1 || true",
  "  rm -rf \"$state\"",
  "}",
  "trap cleanup EXIT",
  "common=\"--db_host=$state --db_user=odoo --data-dir=$state/data --addons-path=/usr/lib/python3/dist-packages/odoo/addons,$addons -d e2e\"",
  "serving() { curl -fsS \"http://127.0.0.1:$port/web/health\" >/dev/null 2>&1; }",
  "serve() {",
  "  if [ \"$keep\" = 1 ]; then",
  "    setsid nohup odoo $common --http-port=\"$port\" --db-filter='^e2e$' --no-database-list --workers=0 >\"$state/odoo.log\" 2>&1 < /dev/null &",
  "  else",
  "    odoo $common --http-port=\"$port\" --db-filter='^e2e$' --no-database-list --workers=0 >\"$state/odoo.log\" 2>&1 &",
  "  fi",
  "  odoo_pid=$!",
  "  echo \"$odoo_pid\" > \"$state/odoo.pid\"",
  "  for i in $(seq 1 60); do",
  "    if serving; then return 0; fi",
  "    sleep 1",
  "  done",
  "  tail -20 \"$state/odoo.log\"",
  "  echo \"odoo-e2e: FAILED \u2014 Odoo did not start\"",
  "  exit 1",
  "}",
  "install() {",
  "  if ! odoo $common \"$@\" --without-demo=all --stop-after-init >\"$state/install.log\" 2>&1; then",
  "    tail -20 \"$state/install.log\"",
  "    echo \"odoo-e2e: FAILED \u2014 $modules did not install\"",
  "    [ \"$keep\" = 1 ] && stop_kept",
  "    exit 1",
  "  fi",
  "}",
  "reused=0",
  "if [ \"$keep\" = 1 ] && [ -f \"$state/modules\" ] && [ \"$(cat \"$state/modules\")\" = \"$modules\" ] && [ -d \"$state/pg\" ]; then",
  "  \"$pgbin/pg_ctl\" -D \"$state/pg\" status >/dev/null 2>&1 || \"$pgbin/pg_ctl\" -D \"$state/pg\" -o \"-k $state -c listen_addresses=''\" -l \"$state/pg.log\" -w start >/dev/null",
  "  if [ \"$(cat \"$state/fingerprint\" 2>/dev/null)\" = \"$fingerprint\" ] && serving; then",
  "    reused=1",
  "    echo \"odoo-e2e: reusing the kept Odoo \u2014 addons/ has not changed since it was served\"",
  "  else",
  "    [ -f \"$state/odoo.pid\" ] && kill \"$(cat \"$state/odoo.pid\")\" 2>/dev/null || true",
  "    for i in $(seq 1 20); do serving || break; sleep 1; done",
  "    echo \"odoo-e2e: addons/ changed \u2014 upgrading $modules in the kept Odoo\"",
  "    install -u \"$modules\"",
  "    echo \"$fingerprint\" > \"$state/fingerprint\"",
  "    serve",
  "    reused=1",
  "  fi",
  "fi",
  "if [ \"$reused\" = 0 ]; then",
  "  [ \"$keep\" = 1 ] && { stop_kept; mkdir -p \"$state\"; }",
  "  \"$pgbin/initdb\" -D \"$state/pg\" -U odoo --auth=trust --locale=C.UTF-8 --encoding=UTF8 >/dev/null",
  "  \"$pgbin/pg_ctl\" -D \"$state/pg\" -o \"-k $state -c listen_addresses=''\" -l \"$state/pg.log\" -w start >/dev/null",
  "  install -i \"$modules\"",
  "  echo \"$modules\" > \"$state/modules\"",
  "  echo \"$fingerprint\" > \"$state/fingerprint\"",
  "  serve",
  "fi",
  "mkdir -p \"$PWD/e2e-results\"",
  "rm -rf \"$PWD/e2e-results/artifacts\"",
  "status=0",
  "BASE_URL=\"http://127.0.0.1:$port\" ODOO_LOGIN=admin ODOO_PASSWORD=admin PLAYWRIGHT_JSON_OUTPUT_NAME=\"$PWD/e2e-results/report.json\" \\",
  "  playwright test \"$@\" --reporter=line,json --output=\"$PWD/e2e-results/artifacts\" > \"$state/e2e.out\" 2>&1 || status=$?",
  "tail -40 \"$state/e2e.out\"",
  "if [ \"$status\" -ne 0 ]; then",
  "  for found in $(find \"$PWD/e2e-results/artifacts\" -name page-at-failure.txt 2>/dev/null | sort); do",
  "    echo",
  "    echo \"=== What the page showed when $(basename \"$(dirname \"$found\")\") failed ===\"",
  "    cat \"$found\"",
  "  done",
  "  [ \"$keep\" = 1 ] && echo \"odoo-e2e: the Odoo is still served at http://127.0.0.1:$port (odoo-e2e --stop to stop it)\"",
  "  echo \"odoo-e2e: FAILED \u2014 the browser tests did not pass (exit $status)\"",
  "  exit 1",
  "fi",
  "[ \"$keep\" = 1 ] && echo \"odoo-e2e: the Odoo is still served at http://127.0.0.1:$port (odoo-e2e --stop to stop it)\"",
  "echo \"odoo-e2e: PASSED \u2014 $modules installed and the browser tests pass\"",
].join('\n') + '\n';

export const KOALA_E2E_SCRIPT = [
  "#!/bin/sh",
  "set -eu",
  "modules=$(for manifest in addons/*/__manifest__.py; do [ -f \"$manifest\" ] && basename \"$(dirname \"$manifest\")\"; done | paste -sd, -)",
  "if [ -z \"$modules\" ]; then",
  "  echo \"koala-e2e: FAILED \u2014 there is no module under addons/ to serve\"",
  "  exit 1",
  "fi",
  "[ $# -gt 0 ] || set -- e2e",
  "exec odoo-e2e \"$modules\" \"$@\"",
].join('\n') + '\n';
